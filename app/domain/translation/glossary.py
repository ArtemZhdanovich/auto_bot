_GLOSSARY: dict[str, str] = {**_BRANDS, **_MODELS, **_TERMS}

# Токены чисто hangul-ные, поэтому границы — «не hangul рядом» (ASCII \b не работает).
_PATTERN = re.compile(
    "(?<![가-힣])(" + "|".join(
        sorted((re.escape(k) for k in _GLOSSARY), key=len, reverse=True)
    ) + ")(?![가-힣])"
)


def apply_glossary(text: str) -> str:
    """Заменить известные hangul-токены на канонические написания.

    Многословные ключи («더 뉴») проверяются раньше однословных за счёт
    сортировки по длине. Всё, что не в словаре, остаётся как есть —
    его уже переводит NLLB.
    """
    return _PATTERN.sub(lambda m: _GLOSSARY[m.group(1)], text)

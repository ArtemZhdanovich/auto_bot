# Шумные инициали — после ㅁ-финали вставляем пробел (граница имени).
_OBSTRUENT_CHO = set("ㄱㄲㄷㄸㅂㅃㅅㅆㅈㅉㅊㅋㅌㅍㅎ")

_JAMO_CHO = list(_CHO)
_JAMO_JUNG = list(_JUNG)
_JAMO_JONG = list(_JONG)


def _syllable(ch: str) -> tuple[str, str, str]:
    """Разбор одного слога хангыля → (инициаль, медьаль, финаль)."""
    n = ord(ch) - 0xAC00
    jong = n % 28
    jung = (n // 28) % 21
    cho = n // (28 * 21)
    return (_JAMO_CHO[cho], _JAMO_JUNG[jung], _JAMO_JONG[jong])


def translit(text: str) -> str:
    """Хангыль → кириллица (латиница/цифры/пунктуация не трогаются)."""
    out: list[str] = []
    syllables = [ch for ch in text if 0xAC00 <= ord(ch) <= 0xD7A3]
    idx = 0
    for ch in text:
        if not 0xAC00 <= ord(ch) <= 0xD7A3:
            out.append(ch)
            continue
        cho, jung, jong = _syllable(ch)
        out.append(_CHO[cho] + _JUNG[jung] + _JONG[jong])
        nxt = syllables[idx + 1] if idx + 1 < len(syllables) else None
        if nxt is not None:
            n_cho, _, _ = _syllable(nxt)
            if (jong == "ㅇ" and n_cho == "ㅇ") or (
                jong == "ㅁ" and n_cho in _OBSTRUENT_CHO
            ):
                out.append(" ")
        idx += 1
    return "".join(out)


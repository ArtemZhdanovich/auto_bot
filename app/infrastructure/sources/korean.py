"""Хангыль → русский: карты слов + слоговая транслитерация.

Зачем: Encar отдаёт марку/модель/цвет, имя инспектора, центр диагностики
и примечания к дефектам по-корейски. В миниаппе корейского быть не должно —
всё прогоняется через `dehangul()` (карты известных слов + транслитерация
остатка по мотивам системы Концевича, упрощённо).

Правила транслитерации (упрощённые):
- слог = инициаль + медьаль (+ финаль); инициаль ㅇ не пишется;
- финаль ㅇ → «н»;
- пробел внутри корейского слова вставляется, если предыдущий слог
  заканчивается на ㅇ и следующий начинается с гласной (김대원 → «ким тэн вон»),
  либо предыдущий заканчивается на ㅁ, а следующий начинается на шумной
  (김재근 → «ким чэгын»);
- регистр: каждое слово с кириллицей капитализируется в `dehangul()`.
"""


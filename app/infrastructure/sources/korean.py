_HANGUL_RE = re.compile(r"[\uAC00-\uD7A3]")
_WORD_ORDER: list[tuple[str, str]] = sorted(
    list(_PHRASES.items()) + list(_WORDS.items()), key=lambda kv: -len(kv[0])
)
_MULTI_SPACE = re.compile(r"\s{2,}")
_SPACE_PAREN = re.compile(r"\s*\(")
_EMPTY_PAREN = re.compile(r"\(\)\s*")
_SPACE_PUNCT = re.compile(r"\s+([,:;)])")
_DIGIT_CYR = re.compile(r"(\d)([а-яё])")
_CYRILLIC = re.compile(r"[а-яё]")


def _substitute(text: str, pairs: Iterable[tuple[str, str]]) -> str:
    for src, dst in pairs:
        if src in text:
            text = text.replace(src, dst)
    return text


def dehangul(text: str, extra: Mapping[str, str] | None = None) -> str:
    """Корейские фрагменты → русский (карты + транслитерация остатка).

    Args:
        text: исходная строка (любая смесь).
        extra: дополнительные замены поверх базовых карт.

    Returns:
        Строка без хангыля; латиница/цифры не меняются.
    """
    if not text:
        return text
    s = str(text)
    pairs = _WORD_ORDER if not extra else sorted(
        list(_WORD_ORDER) + list(extra.items()), key=lambda kv: -len(kv[0])
    )
    s = _substitute(s, pairs)
    if _HANGUL_RE.search(s):
        s = translit(s)
    s = _MULTI_SPACE.sub(" ", s).strip()
    s = _EMPTY_PAREN.sub("", s)
    s = _SPACE_PUNCT.sub(r"\1", s)
    s = re.sub(r"([а-яё])\(", r"\1 (", s)  # «техосмотра(ким» → «техосмотра (ким»
    s = _DIGIT_CYR.sub(r"\1 \2", s)
    # капитализация только первого слова (стиль «как в предложении»:
    # заметки «цилиндр блок — подтекание» не должны стать Title Case)
    if s and _CYRILLIC.match(s[0]):
        s = s[0].upper() + s[1:]
    elif s.startswith("(") and len(s) > 1 and _CYRILLIC.match(s[1]):
        s = "(" + s[1].upper() + s[2:]
    return s


def has_hangul(text: object) -> bool:
    """True, если в строке есть хангыль."""
    return isinstance(text, str) and bool(_HANGUL_RE.search(text))


# --- узкие обёртки ----------------------------------------------------------


def ru_make(value: object) -> str | None:
    """Марка («도요타» → Toyota)."""
    if value is None:
        return None
    return dehangul(str(value)) or None


def ru_model(value: object) -> str | None:
    """Модель («더 뉴 그랜저 IG» → New Grandeur IG)."""
    if value is None:
        return None
    return dehangul(str(value), extra={"더": ""}) or None  # одиночное «더» — мусор


def ru_color(value: object) -> str | None:
    """Цвет («진주색» → перламутровый); в нижнем регистре — как другие цвета."""
    if value is None:
        return None
    s = dehangul(str(value))
    return s[0].lower() + s[1:] if s else None
